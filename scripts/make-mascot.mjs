// Turns the Yap cat drawings in assets/mascot/*.svg into src/components/mascot/mascot-art.ts,
// so the app draws them with react-native-svg and needs no extra bundler setup.
//
//   npm run mascot
//
// Edit an SVG (by hand or in any vector editor), re-run this and commit both files.
// Each file name becomes a pose name: assets/mascot/dizzy.svg is <Mascot pose="dizzy" />.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = join(root, 'assets/mascot');
const outFile = join(root, 'src/components/mascot/mascot-art.ts');

const files = readdirSync(sourceDir)
  .filter((file) => file.endsWith('.svg'))
  .sort();

const entries = files.map((file) => {
  const svg = readFileSync(join(sourceDir, file), 'utf8')
    // Titles and comments are for people reading the source; the app doesn't need them.
    .replace(/<title>.*?<\/title>/gs, '')
    .replace(/<!--.*?-->/gs, '')
    .replace(/\s*\n\s*/g, ' ')
    .trim();
  // SVG attributes use double quotes, so a single-quoted string keeps the markup readable.
  const quoted = svg.replaceAll('\\', '\\\\').replaceAll("'", "\\'");
  return `  ${basename(file, '.svg')}:\n    '${quoted}',`;
});

const output = `// Generated by scripts/make-mascot.mjs from assets/mascot/*.svg. Don't edit this file:
// change the SVG and run \`npm run mascot\`.

export const MASCOT_ART = {
${entries.join('\n')}
} as const;
`;

writeFileSync(outFile, output);
console.log(`Wrote ${files.length} poses to ${outFile.slice(root.length + 1)}`);
